export interface QuizItem {
  id?: number | string;
  chapter?: string;
  단원?: string;
  question_number?: string;
  "문제 번호"?: string;
  question?: string;
  퀴즈?: string;
  source_reference?: string;
  "근거 페이지"?: string;
  answer_and_explanation?: string;
  답안?: string;
  [key: string]: unknown;
}

export function getQuizChapter(quiz: QuizItem): string {
  return (quiz["단원"] as string) || (quiz.chapter as string) || "";
}

export function getQuizSource(quiz: QuizItem): string {
  return (quiz["근거 페이지"] as string) || (quiz.source_reference as string) || "";
}

export function getQuizQuestion(quiz: QuizItem): string {
  return (quiz["퀴즈"] as string) || (quiz.question as string) || "";
}

export function getQuizAnswer(quiz: QuizItem): string {
  return (quiz["답안"] as string) || (quiz.answer_and_explanation as string) || "";
}

export function getQuizNumberLabel(quiz: QuizItem, idx: number = 0): string {
  if (quiz["문제 번호"]) return String(quiz["문제 번호"]);
  if (quiz.question_number) return String(quiz.question_number);
  if (quiz.id != null) return `문제 ${String(quiz.id).padStart(2, "0")}`;
  return `문제 ${String(idx + 1).padStart(2, "0")}`;
}

export function formatQuizToMarkdown(quiz: QuizItem, idx: number = 0): string {
  const qNum = getQuizNumberLabel(quiz, idx);
  const chapter = getQuizChapter(quiz);
  const source = getQuizSource(quiz);
  const question = getQuizQuestion(quiz);
  const answer = getQuizAnswer(quiz);

  const metaList: string[] = [];
  if (chapter) metaList.push(`**단원**: ${chapter}`);
  if (source) metaList.push(`**근거 페이지**: ${source}`);
  const meta = metaList.join("  \n");

  return `### 📌 ${qNum}
${meta ? `> ${meta}\n` : ""}
#### 📝 퀴즈 (문제)
${question || "(문제 내용 없음)"}

---

#### 💡 모범 답안 및 해설
${answer || "(답안 내용 없음)"}
`;
}

